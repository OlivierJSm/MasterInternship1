def sample_scc_dist(x1, x2, bin_size, h=1, d_bp_max=1_000_000, b_down_sample=False, 
                   chr_names = None, chr_exclude = None, chr_lengths = None):
    
    '''
        Takes two lists of .mcool/.cool files and returns a distance matrix for all contact
        map comparisons possible between the arrays. Uses a standard average SCC if no
        chromosome lengths are provided, uses a weighted average if they are.

        Parameters
        ----------
        x1 : list[str]        
            A list of all .mcool/.cool files.
        x2 : list[str]         
            A list of all .mcool/.cool files.
        bin_size : int
            Bin size in both mcool files that will be used to compute the SCC.
            If inputs are .cool files, this parameter is ignored.
        h : int         
            The smoothing parameter used for the 2D mean filter smoothing.
            Default = 1.
        d_bp_max : int 
            The maximum genomic distance between contacts that will be considered for
            calculating the SCC.
            Default = 1_000_000
        b_down_samp : bool
            Determines if the input file with more contacts should be downsized
            to the same number of contacts as the other input file.
            Default = False.
        chr_names : list[str]       
            Chromosomes whose SCC should be calculated.
            Default = None, takes all chromosomes.
        chr_exclude : set[str]    
            Chromosomes that should be ignored for SCC calculation.
            Default = None, excludes no chromosomes.
        chr_lengths : list[int] 
            The lengths of the chromosomes for the included data.
            Default = None, uses a non-weighted average instead.
        
        Returns
        -------
        1 - dist : np.ndarray
            Distance matrix between all included .(m)cool files.

    '''
    # Getting list lengths
    n1 = len(x1)
    n2 = len(x2)
    
    # Define distance matrix
    dist = np.zeros((n1, n2))

    # Looping over all combinations
    for i in range(n1):  # Loop over indices to enable appending to dist matrix
        cmap1 = x1[i]

        for j in range(n2):
            cmap2 = x2[j]

            # Calculate SCCs
            scc = calc_scc_file(cmap1, cmap2, bin_size, h, d_bp_max, b_down_sample, 
                           chr_names, chr_exclude)
            
            # Averages handling
            if chr_lengths == None:
                scc_avg = avg_scc(scc)
            else:
                scc_avg = avg_scc_weighted(scc, chr_lengths)
            
            # Adding to distance matrix
            dist[i, j] = scc_avg

    return 1 - dist # Subtract dist from 1 to get distances between samples instead of similarities